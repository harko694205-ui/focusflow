/**
 * Core domain types. Pure data — no React, no Dexie.
 * Conventions: instants are epoch ms, durations are minutes.
 */

export type ID = string;
export type Instant = number;
export type Minutes = number;

/** 0 = urgent … 3 = low */
export type Priority = 0 | 1 | 2 | 3;
/** 1 = easy, 2 = medium, 3 = hard. Hard work is placed into peak focus windows (Phase 2). */
export type Difficulty = 1 | 2 | 3;
export type TaskStatus = 'todo' | 'in_progress' | 'done';

export interface Category {
  id: ID;
  name: string;
  /** Token name from CATEGORY_COLORS, e.g. "iris". */
  color: CategoryColor;
  order: number;
  createdAt: Instant;
}

export interface Task {
  id: ID;
  /** Human-friendly sequential number, displayed as FF-<seq>. */
  seq: number;
  title: string;
  notes: string;
  categoryId: ID;
  status: TaskStatus;
  priority: Priority;
  difficulty: Difficulty;
  estimate: Minutes;
  deadline: Instant;
  createdAt: Instant;
  updatedAt: Instant;
  completedAt: Instant | null;
  /** Tasks that must be finished before this one can start ("blocked by"). Optional for older records. */
  dependsOn?: ID[];
  /** Times the deadline was pushed later (history for Insights). */
  postponed?: number;
  /** Times its scheduled work was moved to a later day. */
  rescheduled?: number;
  /** Deadline before the first postponement. */
  firstDeadline?: Instant;
  /** Set for study sessions generated by the exam prep planner. */
  examId?: ID;
  /** Calendar UID of the BruinLearn/Canvas item it was imported from (re-imports update it). */
  sourceUid?: string;
}

/** The user-editable part of a task. */
export type TaskDraft = Pick<Task, 'title' | 'notes' | 'categoryId' | 'priority' | 'difficulty' | 'estimate' | 'deadline'> & {
  status?: TaskStatus;
  dependsOn?: ID[];
  examId?: ID;
  /** Calendar UID of the BruinLearn/Canvas item it was imported from (re-imports update it). */
  sourceUid?: string;
};

/**
 * A span of time on the timeline. `task` blocks schedule work for a task (a task may have several);
 * `event` blocks are fixed commitments (meetings, appointments) with their own title.
 * Blocks never cross local midnight.
 */
export interface TimeBlock {
  id: ID;
  kind: 'task' | 'event';
  /** Set for kind = 'task'. */
  taskId: ID | null;
  /** Set for kind = 'event'. */
  title: string;
  start: Instant;
  end: Instant;
  createdAt: Instant;
  updatedAt: Instant;
  /** Set on the event block that shows an exam on the timeline. */
  examId?: ID;
  /** Set on the event blocks generated from a recurring class. */
  classId?: ID;
  /** Course of a class event (its colour on the timeline). */
  categoryId?: ID;
}

export type CategoryColor = 'iris' | 'teal' | 'amber' | 'rose' | 'sky' | 'lime' | 'violet' | 'slate';

/**
 * Time actually spent on a task — recorded by the focus timer or logged by hand. This is the
 * "actual" in estimate-vs-actual, and the source for focus-hour insights.
 */
export interface WorkSession {
  id: ID;
  taskId: ID;
  start: Instant;
  end: Instant;
  source: 'timer' | 'manual';
  createdAt: Instant;
}

/** The running focus timer (at most one). */
export interface ActiveTimer {
  taskId: ID;
  start: Instant;
}

/** How well you know an exam topic: 1 = shaky 😬, 2 = okay 🙂, 3 = solid 😎. */
export type Confidence = 1 | 2 | 3;

export interface ExamTopic {
  id: ID;
  name: string;
  confidence: Confidence;
}

/**
 * An exam (midterm, final, quiz). Its study sessions are ordinary tasks with `examId` set, so
 * they're scheduled, timed and counted like any other work.
 */
export interface Exam {
  id: ID;
  title: string;
  /** The course. */
  categoryId: ID;
  start: Instant;
  duration: Minutes;
  location: string;
  /** How much preparation you want in total. */
  prepTarget: Minutes;
  topics: ExamTopic[];
  notes: string;
  createdAt: Instant;
  updatedAt: Instant;
}

export type ExamDraft = Pick<Exam, 'title' | 'categoryId' | 'start' | 'duration' | 'location' | 'prepTarget' | 'topics' | 'notes'>;

/**
 * A weekly class meeting (lecture, discussion, lab…). Its meetings for the term are generated
 * as event blocks on the timeline, so scheduling works around them like any other commitment.
 */
export interface ClassMeeting {
  id: ID;
  /** The course. */
  categoryId: ID;
  /** "Lecture", "Discussion", "Lab"… */
  kind: string;
  /** Weekdays it meets, 0 = Sunday … 6 = Saturday. */
  days: number[];
  /** Minutes from local midnight. */
  start: Minutes;
  end: Minutes;
  location: string;
  createdAt: Instant;
  updatedAt: Instant;
}

export type ClassDraft = Pick<ClassMeeting, 'categoryId' | 'kind' | 'days' | 'start' | 'end' | 'location'>;
